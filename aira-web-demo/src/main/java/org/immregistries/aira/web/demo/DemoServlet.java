package org.immregistries.aira.web.demo;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintWriter;
import java.util.List;
import java.util.Properties;
import org.immregistries.aira.web.AiraDefaults;
import org.immregistries.aira.web.AiraPage;

@WebServlet(name = "DemoServlet", urlPatterns = {""})
public class DemoServlet extends HttpServlet {

  private static final String APPLICATION_NAME = "AIRA Web Demo";
  private static final String APPLICATION_VERSION = loadApplicationVersion();

  private static final List<DemoRecord> DEMO_RECORDS = List.of(
      new DemoRecord("Brand tokens", "Shared CSS", "Ready"),
      new DemoRecord("Servlet resources", "META-INF/resources", "Verified"),
      new DemoRecord("Rendering model", "Shared shell plus servlet content", "Prototype")
  );

  @Override
  protected void doGet(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    response.setCharacterEncoding("UTF-8");
    response.setContentType("text/html;charset=UTF-8");

    AiraPage page = AiraPage.builder()
        .applicationName(APPLICATION_NAME)
        .applicationVersion(APPLICATION_VERSION)
        .documentTitle(APPLICATION_NAME)
        .pageHeading("Reusable AIRA Web Resources")
        .pageIntro("This servlet-generated page demonstrates that a WAR can consume a shared "
            + "AIRA application shell and versioned web resources from Maven dependencies.")
        .contextPath(request.getContextPath())
        .identityHref(AiraDefaults.AIRA_WEBSITE_URL)
        .addNavigationItem("Overview", "/", true)
        .addNavigationItem("Form", "#form-demo", false)
        .addNavigationItem("Table", "#table-demo", false)
        .addNavigationItem("Footer", "#footer-demo", false)
        .addLocalStylesheet("/css/application.css")
        .build();

    try (PrintWriter out = response.getWriter()) {
      page.writeStart(out);
      renderDemoContent(out);
      page.writeEnd(out);
    }
  }

  private static void renderDemoContent(PrintWriter out) {
    out.println("    <div class=\"aira-page-actions demo-page-actions\">");
    out.println("      <a class=\"aira-button aira-button--primary\" href=\"#form-demo\">Start review</a>");
    out.println("      <a class=\"aira-button aira-button--secondary\" href=\"#table-demo\">View status</a>");
    out.println("    </div>");
    out.println("    <div class=\"demo-grid\">");
    out.println("      <div class=\"demo-stack\">");
    writeAlert(out);
    writeForm(out);
    writeTable(out);
    out.println("      </div>");
    writePanel(out);
    out.println("    </div>");
  }

  private static void writeAlert(PrintWriter out) {
    out.println("        <section class=\"aira-alert aira-alert--success\" aria-labelledby=\"status-title\">");
    out.println("          <p class=\"aira-alert__title\" id=\"status-title\">Shared shell loaded</p>");
    out.println("          <p>The page shell is generated by <code>aira-web-components</code>, while this content remains application-generated servlet HTML.</p>");
    out.println("        </section>");
  }

  private static void writeForm(PrintWriter out) {
    out.println("        <section class=\"aira-panel\" id=\"form-demo\" aria-labelledby=\"form-title\">");
    out.println("          <h2 class=\"aira-section-title\" id=\"form-title\">Small form</h2>");
    out.println("          <form method=\"get\" action=\"\">");
    out.println("            <div class=\"aira-field\">");
    out.println("              <label for=\"project-name\">Project name</label>");
    out.println("              <input class=\"aira-input\" id=\"project-name\" name=\"projectName\" value=\"AIRA Web\">");
    out.println("              <div class=\"aira-field-help\">Labels, help text, and controls come from the shared theme.</div>");
    out.println("            </div>");
    out.println("            <div class=\"aira-field\">");
    out.println("              <label for=\"review-status\">Review status</label>");
    out.println("              <select class=\"aira-select\" id=\"review-status\" name=\"reviewStatus\">");
    out.println("                <option>Ready for review</option>");
    out.println("                <option>Needs updates</option>");
    out.println("              </select>");
    out.println("            </div>");
    out.println("            <button class=\"aira-button aira-button--primary\" type=\"submit\">Save draft</button>");
    out.println("          </form>");
    out.println("        </section>");
  }

  private static void writeTable(PrintWriter out) {
    out.println("        <section class=\"aira-panel\" id=\"table-demo\" aria-labelledby=\"table-title\">");
    out.println("          <h2 class=\"aira-section-title\" id=\"table-title\">Resource packaging status</h2>");
    out.println("          <div class=\"aira-table-wrap\">");
    out.println("            <table class=\"aira-table\">");
    out.println("              <thead>");
    out.println("                <tr><th scope=\"col\">Area</th><th scope=\"col\">Mechanism</th><th scope=\"col\">Status</th></tr>");
    out.println("              </thead>");
    out.println("              <tbody>");
    for (DemoRecord record : DEMO_RECORDS) {
      out.println("                <tr><td>" + escapeHtml(record.area()) + "</td><td>"
          + escapeHtml(record.mechanism()) + "</td><td>" + escapeHtml(record.status()) + "</td></tr>");
    }
    out.println("              </tbody>");
    out.println("            </table>");
    out.println("          </div>");
    out.println("        </section>");
  }

  private static void writePanel(PrintWriter out) {
    out.println("      <aside class=\"aira-card\" aria-labelledby=\"panel-title\">");
    out.println("        <h2 class=\"aira-section-title\" id=\"panel-title\">Demo summary</h2>");
    out.println("        <div class=\"demo-stat\">3</div>");
    out.println("        <p>Modules are included in this stage of the Maven build.</p>");
    out.println("        <p class=\"aira-meta\">The small statistic style is application-specific and uses the <code>demo-</code> prefix.</p>");
    out.println("      </aside>");
  }

  private static String loadApplicationVersion() {
    Properties properties = new Properties();
    try (InputStream inputStream = DemoServlet.class.getResourceAsStream("/aira-web-demo.properties")) {
      if (inputStream != null) {
        properties.load(inputStream);
        String version = properties.getProperty("application.version");
        if (version != null && !version.isBlank() && !version.startsWith("${")) {
          return version.trim();
        }
      }
    } catch (IOException ignored) {
      // Fall through to a readable local-development fallback.
    }
    return "development";
  }

  private static String escapeHtml(String value) {
    if (value == null) {
      return "";
    }
    StringBuilder escaped = new StringBuilder(value.length());
    for (int i = 0; i < value.length(); i++) {
      char character = value.charAt(i);
      switch (character) {
        case '&' -> escaped.append("&amp;");
        case '<' -> escaped.append("&lt;");
        case '>' -> escaped.append("&gt;");
        case '"' -> escaped.append("&quot;");
        case '\'' -> escaped.append("&#39;");
        default -> escaped.append(character);
      }
    }
    return escaped.toString();
  }

  private record DemoRecord(String area, String mechanism, String status) {
  }
}
